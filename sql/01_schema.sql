
CREATE TABLE stations (
    id_station      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_station    VARCHAR(20) NOT NULL UNIQUE,
    nom_station     VARCHAR(100) NOT NULL,
    ville           VARCHAR(100) NOT NULL,
    adresse         VARCHAR(255) NOT NULL,
    date_ouverture  DATE NOT NULL
);

CREATE TABLE clients (
    id_client           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prenom              VARCHAR(100) NOT NULL,
    nom                 VARCHAR(100) NOT NULL,
    email               VARCHAR(150) NOT NULL UNIQUE,
    ville               VARCHAR(100) NOT NULL,
    date_inscription    DATE NOT NULL
);

CREATE TABLE techniciens (
    id_technicien   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prenom          VARCHAR(100) NOT NULL,
    nom             VARCHAR(100) NOT NULL,
    email           VARCHAR(150) NOT NULL UNIQUE
);

CREATE TABLE bornes (
    id_borne        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_station      INT NOT NULL REFERENCES stations(id_station),
    code_borne      VARCHAR(30) NOT NULL UNIQUE,
    puissance_kw    INT NOT NULL,
    connecteur      VARCHAR(30) NOT NULL,
    etat            VARCHAR(30) NOT NULL
);

CREATE TABLE vehicules (
    id_vehicule             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_client               INT NOT NULL REFERENCES clients(id_client),
    immatriculation         VARCHAR(20) NOT NULL UNIQUE,
    marque                  VARCHAR(50) NOT NULL,
    modele                  VARCHAR(50) NOT NULL,
    capacite_batterie_kwh   INT NOT NULL
);

CREATE TABLE incidents (
    id_incident         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_borne            INT NOT NULL REFERENCES bornes(id_borne),
    date_signalement    TIMESTAMP NOT NULL,
    date_resolution     TIMESTAMP NULL,
    categorie           VARCHAR(50) NOT NULL,
    gravite             VARCHAR(20) NOT NULL,
    statut              VARCHAR(30) NOT NULL,
    description         TEXT
);

CREATE TABLE sessions_recharge (
    id_session      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_borne        INT NOT NULL REFERENCES bornes(id_borne),
    id_vehicule     INT NOT NULL REFERENCES vehicules(id_vehicule),
    debut_session   TIMESTAMP NOT NULL,
    fin_session     TIMESTAMP NULL,
    energie_kwh     NUMERIC(10, 2) NULL,
    cout_eur        NUMERIC(10, 2) NULL,
    statut          VARCHAR(30) NOT NULL
);

CREATE TABLE interventions (
    id_intervention INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_incident     INT NOT NULL REFERENCES incidents(id_incident),
    id_technicien   INT NOT NULL REFERENCES techniciens(id_technicien),
    date_debut      TIMESTAMP NOT NULL,
    date_fin        TIMESTAMP NULL,
    statut          VARCHAR(30) NOT NULL,
    compte_rendu    TEXT
);

CREATE TABLE paiements (
    id_paiement     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_session      INT NOT NULL REFERENCES sessions_recharge(id_session),
    date_paiement   TIMESTAMP NOT NULL,
    montant_eur     NUMERIC(10, 2) NOT NULL,
    mode_paiement   VARCHAR(30) NOT NULL,
    statut          VARCHAR(30) NOT NULL
);